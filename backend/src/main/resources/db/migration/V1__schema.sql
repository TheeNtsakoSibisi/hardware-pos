-- Hardware store POS: core schema.
--
-- Money: every amount is NUMERIC(12,2) in rands, VAT-inclusive unless the column
-- name says otherwise. Quantities are NUMERIC(12,3) because stock is sold by the
-- metre, kilogram and cubic metre as well as by the unit.
--
-- Sales are append-only: a sale is never edited after capture. A correction is a
-- new sale (a refund) that references the original. Stock on hand is therefore
-- derived from stock_movement rather than stored on the product row.

CREATE TABLE staff (
    id            BIGSERIAL PRIMARY KEY,
    username      VARCHAR(40)  NOT NULL UNIQUE,
    display_name  VARCHAR(80)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(16)  NOT NULL CHECK (role IN ('CASHIER', 'MANAGER', 'OWNER')),
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE product (
    id               BIGSERIAL PRIMARY KEY,
    sku              VARCHAR(20)   NOT NULL UNIQUE,
    barcode          VARCHAR(20)   UNIQUE,
    name             VARCHAR(120)  NOT NULL,
    category         VARCHAR(40)   NOT NULL,
    unit             VARCHAR(10)   NOT NULL,
    -- TRUE for items sold in fractions (per metre, kg, m3); FALSE for whole units.
    decimal_qty      BOOLEAN       NOT NULL DEFAULT FALSE,
    retail_incl_vat  NUMERIC(12,2) NOT NULL CHECK (retail_incl_vat >= 0),
    cost_excl_vat    NUMERIC(12,2) NOT NULL CHECK (cost_excl_vat >= 0),
    reorder_level    NUMERIC(12,3) NOT NULL DEFAULT 0,
    serialised       BOOLEAN       NOT NULL DEFAULT FALSE,
    active           BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE INDEX idx_product_category ON product (category);
CREATE INDEX idx_product_name_lower ON product (lower(name));

CREATE TABLE stock_movement (
    id         BIGSERIAL PRIMARY KEY,
    product_id BIGINT        NOT NULL REFERENCES product (id),
    qty_delta  NUMERIC(12,3) NOT NULL,
    reason     VARCHAR(20)   NOT NULL CHECK (reason IN ('SALE', 'RECEIPT', 'RETURN', 'COUNT', 'WRITE_OFF', 'OPENING')),
    reference  VARCHAR(40),
    created_at TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE INDEX idx_stock_movement_product ON stock_movement (product_id);

-- Trade discount tiers. Kept as data so the owner can add a tier without a
-- release; the discount is applied to the VAT-inclusive shelf price.
CREATE TABLE price_tier (
    code             VARCHAR(2)   PRIMARY KEY,
    name             VARCHAR(40)  NOT NULL,
    discount_percent NUMERIC(5,2) NOT NULL CHECK (discount_percent >= 0 AND discount_percent < 100)
);

CREATE TABLE contractor_account (
    id           BIGSERIAL PRIMARY KEY,
    code         VARCHAR(10)   NOT NULL UNIQUE,
    name         VARCHAR(120)  NOT NULL,
    contact_name VARCHAR(80),
    phone        VARCHAR(20),
    email        VARCHAR(120),
    vat_no       VARCHAR(20),
    -- Trade tier decides the discount off shelf price (see price_tier table).
    price_tier   VARCHAR(2)    NOT NULL REFERENCES price_tier (code),
    credit_limit NUMERIC(12,2) NOT NULL CHECK (credit_limit >= 0),
    terms_days   INT           NOT NULL DEFAULT 30 CHECK (terms_days > 0),
    status       VARCHAR(12)   NOT NULL CHECK (status IN ('ACTIVE', 'ON_HOLD', 'CLOSED')),
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE TABLE authorised_buyer (
    id             BIGSERIAL PRIMARY KEY,
    account_id     BIGINT        NOT NULL REFERENCES contractor_account (id),
    name           VARCHAR(80)   NOT NULL,
    role_title     VARCHAR(40),
    pin_hash       VARCHAR(100)  NOT NULL,
    -- NULL means no per-sale ceiling for this buyer.
    per_sale_limit NUMERIC(12,2) CHECK (per_sale_limit IS NULL OR per_sale_limit > 0),
    active         BOOLEAN       NOT NULL DEFAULT TRUE
);

CREATE INDEX idx_buyer_account ON authorised_buyer (account_id);

CREATE TABLE job_site (
    id          BIGSERIAL PRIMARY KEY,
    account_id  BIGINT       NOT NULL REFERENCES contractor_account (id),
    code        VARCHAR(12)  NOT NULL UNIQUE,
    description VARCHAR(160) NOT NULL,
    active      BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE INDEX idx_job_account ON job_site (account_id);

CREATE TABLE sale (
    id              BIGSERIAL PRIMARY KEY,
    -- Generated by the till, including while offline. Makes sync idempotent:
    -- replaying a queued sale returns the sale already captured.
    client_uuid     UUID          NOT NULL UNIQUE,
    -- Prefixed per till (T1-000123) so two offline tills cannot collide.
    document_no     VARCHAR(20)   NOT NULL UNIQUE,
    till_id         VARCHAR(8)    NOT NULL,
    sale_type       VARCHAR(10)   NOT NULL CHECK (sale_type IN ('WALK_IN', 'ACCOUNT')),
    account_id      BIGINT        REFERENCES contractor_account (id),
    buyer_id        BIGINT        REFERENCES authorised_buyer (id),
    job_id          BIGINT        REFERENCES job_site (id),
    order_ref       VARCHAR(30),
    customer_name   VARCHAR(120),
    customer_vat_no VARCHAR(20),
    total_incl_vat  NUMERIC(12,2) NOT NULL,
    vat_amount      NUMERIC(12,2) NOT NULL,
    due_date        DATE,
    override_reason VARCHAR(200),
    override_by     VARCHAR(40),
    captured_by     VARCHAR(40)   NOT NULL,
    occurred_at     TIMESTAMPTZ   NOT NULL,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT sale_account_fields CHECK (
        (sale_type = 'ACCOUNT' AND account_id IS NOT NULL AND buyer_id IS NOT NULL AND due_date IS NOT NULL)
            OR
        (sale_type = 'WALK_IN' AND account_id IS NULL AND buyer_id IS NULL AND due_date IS NULL)
    )
);

CREATE INDEX idx_sale_account_date ON sale (account_id, occurred_at);
CREATE INDEX idx_sale_occurred ON sale (occurred_at);

CREATE TABLE sale_line (
    id                  BIGSERIAL PRIMARY KEY,
    sale_id             BIGINT        NOT NULL REFERENCES sale (id) ON DELETE CASCADE,
    line_no             INT           NOT NULL,
    product_id          BIGINT        NOT NULL REFERENCES product (id),
    description         VARCHAR(120)  NOT NULL,
    qty                 NUMERIC(12,3) NOT NULL CHECK (qty > 0),
    unit                VARCHAR(10)   NOT NULL,
    unit_price_incl_vat NUMERIC(12,2) NOT NULL CHECK (unit_price_incl_vat >= 0),
    line_total_incl_vat NUMERIC(12,2) NOT NULL CHECK (line_total_incl_vat >= 0),
    UNIQUE (sale_id, line_no)
);

CREATE TABLE sale_tender (
    id            BIGSERIAL PRIMARY KEY,
    sale_id       BIGINT        NOT NULL REFERENCES sale (id) ON DELETE CASCADE,
    tender_type   VARCHAR(10)   NOT NULL CHECK (tender_type IN ('CASH', 'CARD', 'EFT')),
    amount        NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    reference     VARCHAR(40),
    cash_received NUMERIC(12,2),
    change_given  NUMERIC(12,2)
);

CREATE TABLE account_payment (
    id           BIGSERIAL PRIMARY KEY,
    payment_no   VARCHAR(20)   NOT NULL UNIQUE,
    account_id   BIGINT        NOT NULL REFERENCES contractor_account (id),
    payment_date DATE          NOT NULL,
    amount       NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    method       VARCHAR(10)   NOT NULL CHECK (method IN ('CASH', 'CARD', 'EFT')),
    reference    VARCHAR(40),
    captured_by  VARCHAR(40)   NOT NULL,
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE INDEX idx_payment_account ON account_payment (account_id, payment_date);

-- Which invoice each rand of a payment settled. Written by the allocation
-- service (oldest invoice first) rather than by hand.
CREATE TABLE payment_allocation (
    id         BIGSERIAL PRIMARY KEY,
    payment_id BIGINT        NOT NULL REFERENCES account_payment (id) ON DELETE CASCADE,
    sale_id    BIGINT        NOT NULL REFERENCES sale (id),
    amount     NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    UNIQUE (payment_id, sale_id)
);

CREATE INDEX idx_allocation_sale ON payment_allocation (sale_id);

-- Per-till document numbering. Rows are locked FOR UPDATE when a number is
-- issued, so two concurrent sales on one till cannot take the same number.
CREATE TABLE document_sequence (
    till_id    VARCHAR(8)  NOT NULL,
    doc_type   VARCHAR(10) NOT NULL CHECK (doc_type IN ('SALE', 'INVOICE', 'PAYMENT')),
    next_value BIGINT      NOT NULL DEFAULT 1 CHECK (next_value > 0),
    PRIMARY KEY (till_id, doc_type)
);
