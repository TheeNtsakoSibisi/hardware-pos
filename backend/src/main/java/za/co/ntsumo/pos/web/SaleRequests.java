package za.co.ntsumo.pos.web;

import jakarta.validation.Valid;
import jakarta.validation.constraints.*;
import za.co.ntsumo.pos.sales.TenderType;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.List;
import java.util.UUID;

/** What the till posts when a sale is completed. */
public final class SaleRequests {

    private SaleRequests() {
    }

    public record Line(
            @NotBlank String sku,
            @NotNull @DecimalMin(value = "0.001") BigDecimal qty) {
    }

    public record Tender(
            @NotNull TenderType type,
            @NotNull @DecimalMin(value = "0.01") BigDecimal amount,
            @Size(max = 40) String reference,
            BigDecimal cashReceived) {
    }

    public record WalkInSale(
            /* Generated by the till so a replayed sale is recognised, not duplicated. */
            @NotNull UUID clientUuid,
            @NotBlank @Size(max = 8) String tillId,
            @NotEmpty @Valid List<Line> lines,
            @NotEmpty @Valid List<Tender> tenders,
            /* Set only when the customer asks for a tax invoice in their name. */
            @Size(max = 120) String customerName,
            @Size(max = 20) String customerVatNo,
            /* When the sale actually happened, which may be while the till was offline. */
            Instant occurredAt) {
    }

    public record AccountSale(
            @NotNull UUID clientUuid,
            @NotBlank @Size(max = 8) String tillId,
            @NotBlank String accountCode,
            @NotNull Long buyerId,
            @NotBlank String buyerPin,
            @NotBlank String jobCode,
            @Size(max = 30) String orderRef,
            @NotEmpty @Valid List<Line> lines,
            /* Present only when a manager is approving a sale the rules blocked. */
            @Size(max = 200) String overrideReason,
            @Size(max = 40) String overrideBy,
            Instant occurredAt) {
    }

    /** A batch of sales a till queued while it had no network. */
    public record SyncBatch(
            @Valid List<WalkInSale> walkInSales,
            @Valid List<AccountSale> accountSales) {
    }

    public record PaymentRequest(
            @NotBlank String accountCode,
            @NotNull @DecimalMin(value = "0.01") BigDecimal amount,
            @NotNull TenderType method,
            @Size(max = 40) String reference) {
    }
}
