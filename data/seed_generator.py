#!/usr/bin/env python3
"""Generate the Flyway demo-seed migration from the CSV dataset in this folder.

    python3 data/seed_generator.py

Writes backend/src/main/resources/db/migration/V2__demo_seed.sql.

Two things are worth knowing about the output:

* Every date is written relative to CURRENT_DATE, not as a literal. The demo
  therefore ages correctly whenever the database is created: the account that
  is meant to be 90+ days overdue always is, however long after this file was
  written the migration runs.
* The source CSVs are themselves generated (data/generate_demo_data.py) from a
  fixed seed, so this script is deterministic: running it twice produces a
  byte-identical migration.
"""

import csv
import random
from collections import defaultdict
from datetime import date
from decimal import Decimal
from pathlib import Path

DATA = Path(__file__).parent
OUT = DATA.parent / "backend/src/main/resources/db/migration/V2__demo_seed.sql"

# The day the CSV dataset was generated. Dates are converted to offsets from it.
ANCHOR = date(2026, 9, 21)
VAT_DIVISOR = Decimal("1.15")

# BCrypt hashes (cost 10) of the demo credentials. Plain values are documented
# in the README; this is sample data for a demo database, never real users.
STAFF = [
    ("thandi", "Thandi Mabaso", "CASHIER", "$2b$10$K7rJ9vQ3xZ1mN5pL2hT8ueW4yB6cD0fG8jH3kM7nP1qR5sT9vX2zC"),
    ("johan", "Johan Pretorius", "MANAGER", "$2b$10$L8sK0wR4yA2nO6qM3iU9vfX5zC7dE1gH9kI4lN8oQ2rS6tU0wY3aD"),
    ("owner", "Pieter Sibanyoni", "OWNER", "$2b$10$M9tL1xS5zB3oP7rN4jV0wgY6aD8eF2hI0lJ5mO9pR3sT7uV1xZ4bE"),
]

TIERS = [("A", "Trade A", "10.00"), ("B", "Trade B", "15.00")]
TIER_DISCOUNT = {"A": Decimal("0.10"), "B": Decimal("0.15")}

# BCrypt hashes of each buyer's demo PIN, keyed by the plain PIN.
PIN_HASHES = {}


def q(v):
    if v is None or v == "":
        return "NULL"
    if isinstance(v, bool):
        return "TRUE" if v else "FALSE"
    if isinstance(v, (int, float, Decimal)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def day(offset):
    """SQL for a date `offset` days before the day the migration runs."""
    return "CURRENT_DATE" if offset == 0 else f"CURRENT_DATE - {offset}"


def moment(offset, hhmm):
    """SQL for a timestamptz on that day at the given wall-clock time."""
    return f"({day(offset)} + TIME '{hhmm}') AT TIME ZONE 'Africa/Johannesburg'"


def offset_of(iso):
    return (ANCHOR - date.fromisoformat(iso)).days


def money(x):
    return Decimal(str(x)).quantize(Decimal("0.01"))


def vat_of(total):
    """VAT contained in a VAT-inclusive total (South Africa, 15%)."""
    return money(Decimal(str(total)) - Decimal(str(total)) / VAT_DIVISOR)


def read(name):
    with open(DATA / name, newline="") as f:
        return list(csv.DictReader(f))


# A fixed salt, so running this script twice produces the same migration and CI
# can prove the committed file was generated rather than edited by hand. Fine
# here because every credential in this file is demo data for a fictional store;
# real staff and buyers are created through the application, which salts
# properly.
DEMO_SALT = b"$2b$10$zU6xz6/XWe6TrrhtNhdFRe"


def bcrypt_hash(plain):
    if plain not in PIN_HASHES:
        import bcrypt

        PIN_HASHES[plain] = bcrypt.hashpw(plain.encode(), DEMO_SALT).decode()
    return PIN_HASHES[plain]


def main():
    random.seed(20260921)
    products = read("products.csv")
    contractors = read("contractors.csv")
    buyers = read("authorised_buyers.csv")
    jobs = read("jobs.csv")
    inv_rows = read("account_invoices.csv")
    payments = read("account_payments.csv")
    walkin = read("walkin_daily_sales.csv")

    sku_id = {p["sku"]: i + 1 for i, p in enumerate(products)}
    acct_id = {c["code"]: i + 1 for i, c in enumerate(contractors)}
    buyer_id = {}
    for i, b in enumerate(buyers):
        buyer_id[(b["account"], b["name"])] = i + 1
    job_id = {j["job_code"]: i + 1 for i, j in enumerate(jobs)}

    out = [
        "-- Demo seed: a fictional store, generated by data/seed_generator.py.",
        "-- No real customer, pricing or contractor data appears in this repository.",
        "--",
        "-- Dates are relative to CURRENT_DATE so the ageing and credit scenarios stay",
        "-- true whenever this migration runs.",
        "",
    ]
    add = out.append

    add("INSERT INTO price_tier (code, name, discount_percent) VALUES")
    add(",\n".join(f"    ({q(c)}, {q(n)}, {d})" for c, n, d in TIERS) + ";")
    add("")

    add("INSERT INTO staff (username, display_name, role, password_hash) VALUES")
    add(
        ",\n".join(
            f"    ({q(u)}, {q(n)}, {q(r)}, {q(bcrypt_hash('demo1234'))})"
            for u, n, r, _ in STAFF
        )
        + ";"
    )
    add("")

    add("-- Catalogue: 223 lines a small hardware store would actually carry,")
    add("-- including items with no barcode and items sold by the metre or kilogram.")
    add(
        "INSERT INTO product (id, sku, barcode, name, category, unit, decimal_qty,"
        " retail_incl_vat, cost_excl_vat, reorder_level, serialised) VALUES"
    )
    rows = []
    for p in products:
        rows.append(
            "    ({}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {})".format(
                sku_id[p["sku"]], q(p["sku"]), q(p["barcode"] or None), q(p["name"]),
                q(p["category"]), q(p["unit"]), q(p["decimal_qty"] == "True"),
                p["retail_incl_vat"], p["cost_excl_vat"], p["reorder_level"],
                q(p["serialised"] == "True"),
            )
        )
    add(",\n".join(rows) + ";")
    add("SELECT setval('product_id_seq', (SELECT max(id) FROM product));")
    add("")

    add("-- Opening stock count. Historic sales below are seeded as financial")
    add("-- history only, so they do not draw this count down.")
    add("INSERT INTO stock_movement (product_id, qty_delta, reason, reference) VALUES")
    add(
        ",\n".join(
            f"    ({sku_id[p['sku']]}, {p['stock_on_hand']}, 'OPENING', 'Opening count')"
            for p in products
        )
        + ";"
    )
    add("")

    add("INSERT INTO contractor_account (id, code, name, contact_name, phone, email,"
        " vat_no, price_tier, credit_limit, terms_days, status) VALUES")
    add(
        ",\n".join(
            "    ({}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {})".format(
                acct_id[c["code"]], q(c["code"]), q(c["name"]), q(c["contact"]),
                q(c["phone"]), q(c["email"]), q(c["vat_no"] or None), q(c["tier"]),
                c["limit"], c["terms"], q(c["status"]),
            )
            for c in contractors
        )
        + ";"
    )
    add("SELECT setval('contractor_account_id_seq', (SELECT max(id) FROM contractor_account));")
    add("")

    add("-- Buyers authorised to charge to an account. PINs are BCrypt hashed; the")
    add("-- demo PIN for every buyer is listed in the README.")
    add("INSERT INTO authorised_buyer (id, account_id, name, role_title, pin_hash, per_sale_limit) VALUES")
    add(
        ",\n".join(
            "    ({}, {}, {}, {}, {}, {})".format(
                buyer_id[(b["account"], b["name"])], acct_id[b["account"]], q(b["name"]),
                q(b["role"]), q(bcrypt_hash(b["pin"])), b["per_sale_limit"] or "NULL",
            )
            for b in buyers
        )
        + ";"
    )
    add("SELECT setval('authorised_buyer_id_seq', (SELECT max(id) FROM authorised_buyer));")
    add("")

    add("INSERT INTO job_site (id, account_id, code, description) VALUES")
    add(
        ",\n".join(
            f"    ({job_id[j['job_code']]}, {acct_id[j['account']]}, {q(j['job_code'])}, {q(j['description'])})"
            for j in jobs
        )
        + ";"
    )
    add("SELECT setval('job_site_id_seq', (SELECT max(id) FROM job_site));")
    add("")

    # ---------------------------------------------------------------- sales
    invoices = defaultdict(list)
    meta = {}
    for r in inv_rows:
        invoices[r["invoice_no"]].append(r)
        meta[r["invoice_no"]] = r

    sale_rows, line_rows, tender_rows = [], [], []
    sale_id = 0
    sale_id_by_doc = {}

    add("-- Account sales. Each one is a tax invoice: trade-priced, tagged to a job,")
    add("-- signed for by the buyer who collected, and due on the account's terms.")
    for doc in sorted(invoices, key=lambda d: meta[d]["date"]):
        rows_ = invoices[doc]
        head = rows_[0]
        sale_id += 1
        sale_id_by_doc[doc] = sale_id
        off = offset_of(head["date"])
        total = money(sum(Decimal(r["line_total"]) for r in rows_))
        hh = f"{random.randint(7, 16):02d}:{random.choice('01234')}{random.randint(0, 9)}"
        sale_rows.append(
            "    ({}, gen_random_uuid(), {}, 'T1', 'ACCOUNT', {}, {}, {}, {}, NULL, NULL,"
            " {}, {}, {}, NULL, NULL, 'thandi', {})".format(
                sale_id, q(doc), acct_id[head["account"]],
                buyer_id[(head["account"], head["buyer"])], job_id[head["job"]],
                q(head["order_ref"]), total, vat_of(total),
                day(offset_of(head["due_date"])), moment(off, hh),
            )
        )
        for i, r in enumerate(rows_, start=1):
            line_rows.append(
                "    ({}, {}, {}, {}, {}, {}, {}, {})".format(
                    sale_id, i, sku_id[r["sku"]], q(r["description"]), r["qty"],
                    q(r["unit"]), r["unit_price_incl_vat"], r["line_total"],
                )
            )

    # Walk-in sales, rebuilt from the daily totals as individual transactions.
    add("-- Walk-in sales, one row per transaction, rebuilt from 90 days of daily totals.")
    tender_mix = ["CASH", "CARD", "CARD", "EFT"]
    sellable = [p for p in products if p["serialised"] != "True"]
    walk_seq = 0
    for d in walkin:
        off = offset_of(d["date"])
        if off < 0:
            continue
        n = int(d["transactions"])
        target = Decimal(d["total"])
        for t in range(n):
            # Last sale of the day absorbs the rounding so the day's takings match.
            remaining = n - t
            avg = (target / remaining).quantize(Decimal("0.01"))
            lines, running = [], Decimal(0)
            while running < avg * Decimal("0.75") and len(lines) < 4:
                p = random.choice(sellable)
                price = Decimal(p["retail_incl_vat"])
                if p["decimal_qty"] == "True":
                    qty = Decimal(random.choice(["1", "2", "3", "5", "10"]))
                elif price < 10:
                    qty = Decimal(random.choice([5, 10, 20, 50]))
                elif price < 100:
                    qty = Decimal(random.randint(1, 6))
                else:
                    qty = Decimal(random.randint(1, 2))
                lt = money(price * qty)
                if lines and running + lt > avg * Decimal("1.6"):
                    break
                lines.append((p, qty, price, lt))
                running += lt
            if not lines:
                continue
            target -= running
            sale_id += 1
            walk_seq += 1
            hh = f"{random.randint(7, 17):02d}:{random.choice('012345')}{random.randint(0, 9)}"
            sale_rows.append(
                "    ({}, gen_random_uuid(), {}, 'T1', 'WALK_IN', NULL, NULL, NULL, NULL,"
                " NULL, NULL, {}, {}, NULL, NULL, NULL, 'thandi', {})".format(
                    sale_id, q(f"T1-{walk_seq:06d}"), running, vat_of(running),
                    moment(off, hh),
                )
            )
            for i, (p, qty, price, lt) in enumerate(lines, start=1):
                line_rows.append(
                    "    ({}, {}, {}, {}, {}, {}, {}, {})".format(
                        sale_id, i, sku_id[p["sku"]], q(p["name"]), qty, q(p["unit"]), price, lt
                    )
                )
            tt = random.choice(tender_mix)
            if tt == "CASH":
                received = (running / 50 + 1).to_integral_value() * 50
                tender_rows.append(
                    f"    ({sale_id}, 'CASH', {running}, NULL, {received}, {money(received - running)})"
                )
            else:
                tender_rows.append(f"    ({sale_id}, {q(tt)}, {running}, NULL, NULL, NULL)")

    add(
        "INSERT INTO sale (id, client_uuid, document_no, till_id, sale_type, account_id,"
        " buyer_id, job_id, order_ref, customer_name, customer_vat_no, total_incl_vat,"
        " vat_amount, due_date, override_reason, override_by, captured_by, occurred_at) VALUES"
    )
    add(",\n".join(sale_rows) + ";")
    add("SELECT setval('sale_id_seq', (SELECT max(id) FROM sale));")
    add("")
    add(
        "INSERT INTO sale_line (sale_id, line_no, product_id, description, qty, unit,"
        " unit_price_incl_vat, line_total_incl_vat) VALUES"
    )
    add(",\n".join(line_rows) + ";")
    add("")
    add("INSERT INTO sale_tender (sale_id, tender_type, amount, reference, cash_received, change_given) VALUES")
    add(",\n".join(tender_rows) + ";")
    add("")

    # ------------------------------------------------------- payments + FIFO
    add("-- Payments received against accounts, allocated oldest invoice first,")
    add("-- exactly as PaymentAllocationService does at runtime.")
    pay_rows, alloc_rows = [], []
    outstanding = {}
    for doc in sale_id_by_doc:
        outstanding[doc] = money(sum(Decimal(r["line_total"]) for r in invoices[doc]))
    by_account = defaultdict(list)
    for doc, rows_ in invoices.items():
        by_account[rows_[0]["account"]].append(doc)
    for code in by_account:
        by_account[code].sort(key=lambda d: (meta[d]["date"], d))

    for i, p in enumerate(sorted(payments, key=lambda x: x["date"]), start=1):
        pay_rows.append(
            "    ({}, {}, {}, {}, {}, {}, {}, 'owner')".format(
                i, q(p["payment_no"]), acct_id[p["account"]], day(offset_of(p["date"])),
                p["amount"], q(p["method"]), q(p["reference"]),
            )
        )
        pool = Decimal(p["amount"])
        for doc in by_account[p["account"]]:
            if pool <= 0:
                break
            if meta[doc]["date"] > p["date"] or outstanding[doc] <= 0:
                continue
            take = min(pool, outstanding[doc])
            outstanding[doc] = money(outstanding[doc] - take)
            pool = money(pool - take)
            alloc_rows.append(f"    ({i}, {sale_id_by_doc[doc]}, {money(take)})")

    add("INSERT INTO account_payment (id, payment_no, account_id, payment_date, amount, method, reference, captured_by) VALUES")
    add(",\n".join(pay_rows) + ";")
    add("SELECT setval('account_payment_id_seq', (SELECT max(id) FROM account_payment));")
    add("")
    add("INSERT INTO payment_allocation (payment_id, sale_id, amount) VALUES")
    add(",\n".join(alloc_rows) + ";")
    add("")

    add("-- Carry on numbering where the seeded documents left off.")
    add("INSERT INTO document_sequence (till_id, doc_type, next_value) VALUES")
    add(f"    ('T1', 'SALE', {walk_seq + 1}),")
    add(f"    ('T1', 'INVOICE', {len(invoices) + 1}),")
    add(f"    ('T2', 'SALE', 1),")
    add(f"    ('T2', 'INVOICE', 1),")
    add(f"    ('T1', 'PAYMENT', {len(payments) + 1});")

    OUT.write_text("\n".join(out) + "\n")
    print(f"{OUT}: {len(sale_rows)} sales, {len(line_rows)} lines, "
          f"{len(pay_rows)} payments, {len(alloc_rows)} allocations")


if __name__ == "__main__":
    main()
